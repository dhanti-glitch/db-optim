# ── Run optimasi ─────────────────────────────────────────────────────────────
if run_btn:
    flow, dist, dept_names = DATASETS[dataset_choice]
    n = len(dept_names)

    st.session_state.running = True
    st.session_state.stop_event = threading.Event()
    st.session_state.result = None

    random.seed(seed_val)
    np.random.seed(seed_val)

    # UI progress
    st.markdown(f'<div class="info-box">⚙️ Menjalankan optimasi untuk <b>{dataset_choice}</b> …</div>',
                unsafe_allow_html=True)

