    status_text   = st.empty()
    live_col1, live_col2 = st.columns(2)
    live_best_ph  = live_col1.empty()
    live_avg_ph   = live_col2.empty()

    riwayat_best_live = []
    riwayat_avg_live  = []
    chart_ph = st.empty()

    def cb(gen, max_g, best_z, avg_z):
        riwayat_best_live.append(best_z)
        riwayat_avg_live.append(avg_z)
        pct = gen / max_g
        progress_bar.progress(pct)
        status_text.markdown(
            f'<p class="progress-label">Generasi <b>{gen}</b> / {max_g} &nbsp;|&nbsp; '
            f'Best Z = <b>{best_z:,.0f}</b> &nbsp;|&nbsp; Avg Z = {avg_z:,.0f}</p>',
            unsafe_allow_html=True
        )
        live_best_ph.metric("Best Z (sekarang)", f"{best_z:,.0f}")
        live_avg_ph.metric("Avg Z (sekarang)", f"{avg_z:,.0f}")
        # Update chart tiap 25 generasi agar tidak lambat
        if gen % 25 == 0 or gen == max_g:
            fig = plot_konvergensi(riwayat_best_live, riwayat_avg_live, dataset_choice)
            chart_ph.plotly_chart(fig, use_container_width=True, key=f"live_{gen}")

    t_start = time.time()
    best_k, best_z, best_f, riwayat_best, riwayat_avg, elapsed = algoritma_genetika(
        flow, dist, dept_names,
        popsize=popsize, elite_count=elite_count,
        pc=pc, pm=pm, max_gen=max_gen,
        progress_callback=cb,
        stop_event=st.session_state.stop_event
    )

    kontribusi = hitung_kontribusi(best_k, flow, dist)

    st.session_state.result = {
        "dataset":       dataset_choice,
        "flow":          flow,
        "dist":          dist,
        "dept_names":    dept_names,
        "best_k":        best_k,
        "best_z":        best_z,
        "best_f":        best_f,
        "riwayat_best":  riwayat_best,
        "riwayat_avg":   riwayat_avg,
        "elapsed":       elapsed,
        "kontribusi":    kontribusi,
        "params":        dict(popsize=popsize, elite_count=elite_count,
                              pc=pc, pm=pm, max_gen=max_gen, seed=seed_val),
    }
    st.session_state.running = False
    progress_bar.progress(1.0)
